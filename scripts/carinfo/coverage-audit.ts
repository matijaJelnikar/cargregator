// Compare an explicit research backlog with a read-only catalogue snapshot. No AI calls or database writes.
// node scripts/carinfo/coverage-audit.ts --snapshot data-raw/carinfo/catalogue-audit/snapshot-20261103.json
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { MAKES } from "../../src/data/makes.ts";
import CANDIDATES from "./coverage-candidates.json" with { type: "json" };

export interface CatalogueGeneration {
  model_id: string;
  slug: string;
  name: string;
  year_from: number;
  year_to: number | null;
  status: string;
}
export interface CoverageCandidate {
  model_id: string;
  slug: string | null;
  name: string;
  year_from: number;
  year_to: number;
  research: string;
  aliases?: string[];
}

export function auditCoverage(generations: CatalogueGeneration[], candidates: CoverageCandidate[], taxonomy: Set<string>) {
  return candidates.map((candidate) => {
    const sameModel = generations.filter((g) => g.model_id === candidate.model_id);
    const slugs = new Set([candidate.slug, ...(candidate.aliases ?? [])]);
    const existing = candidate.slug === null ? sameModel : sameModel.filter((g) => slugs.has(g.slug));
    const state = existing.length ? "present" : !taxonomy.has(candidate.model_id) ? "missing-model" : "missing-generation";
    return { ...candidate, state, existing: existing.map((g) => `${g.slug} (${g.status})`), current: sameModel.map((g) => `${g.name} (${g.year_from}–${g.year_to ?? "present"})`) };
  });
}

export function coverageMarkdown(generations: CatalogueGeneration[], rows: ReturnType<typeof auditCoverage>, date: string) {
  const missing = rows.filter((r) => r.state !== "present");
  const models = new Set(generations.map((g) => g.model_id));
  const section = (state: string) => missing.filter((r) => r.state === state).map((r) =>
    `| ${r.name} | ${r.year_from}–${r.year_to} | \`${r.model_id}${r.slug ? `/${r.slug}` : ""}\` | ${r.research === "pilot-sourced" ? "Pilot researched; SQL prepared, not loaded" : "Absent in snapshot; identity/years/engines need sources"} |`,
  ).join("\n");
  return `# Missing car catalogue backlog

Snapshot: ${date}. Generated by \`scripts/carinfo/coverage-audit.ts\` from a read-only production snapshot and \`coverage-candidates.json\`.

The catalogue contains **${generations.length} generations across ${models.size} models**. The candidate list identifies **${missing.length} absent entries**: ${missing.filter((r) => r.state === "missing-generation").length} generation candidates and ${missing.filter((r) => r.state === "missing-model").length} model candidates.

Scope: an initial backlog of European cars sold during or after 2000, prioritising older gaps. This is not a complete inventory of every European car or new model launch. Except for the Legacy pilot, labels and dates are research leads, not verified import data. A generation is matched by an explicit model/slug or alias, never just by overlapping dates. Held-back reports are present generations and must not be reinserted as missing cars.

The likely systemic cause is the 2011–2025 EEA registration input: \`skeleton-prompt.ts\` explicitly groups only those supplied variants. \`knowledge.ts\` fills models without prompts, but does not backfill older generations of models already represented by EEA rows.

## Missing generations of existing models

| Candidate | Provisional years | Target | State |
| --- | --- | --- | --- |
${section("missing-generation")}

## Missing models

These need taxonomy/site-adapter research as well as a generation and report. No bulk taxonomy changes are prepared before the one-car quality review.

| Candidate | Provisional years | Target | State |
| --- | --- | --- | --- |
${section("missing-model")}

## Pilot and next steps

Only **Subaru Legacy IV (BL/BP, 2003–2009)** is being prepared for insertion. See [the pilot review](SUBARU-LEGACY-IV-PILOT.md). Matija inserts its local SQL and compares the sl/en text with existing Sonnet reports before any further summaries or database additions. No Claude calls and no remote writes are part of this pass.

Refresh the read-only snapshot and rerun the audit after additions. The complete machine-readable comparison is local at \`data-raw/carinfo/catalogue-audit/coverage.json\`.
`;
}

async function main() {
  const args = process.argv.slice(2);
  const index = args.indexOf("--snapshot");
  if (index < 0 || !args[index + 1]) throw new Error("usage: coverage-audit.ts --snapshot <read-only generations JSON>");
  const generations = JSON.parse(await readFile(args[index + 1], "utf8")) as CatalogueGeneration[];
  if (!Array.isArray(generations) || generations.some((g) => !g.model_id || !g.slug || !g.status)) throw new Error("Invalid generation snapshot");
  const rows = auditCoverage(generations, CANDIDATES, new Set(MAKES.flatMap((m) => m.models.map((x) => x.id))));
  await mkdir("data-raw/carinfo/catalogue-audit", { recursive: true });
  await writeFile("data-raw/carinfo/catalogue-audit/coverage.json", JSON.stringify(rows, null, 2) + "\n");
  // Use the snapshot's recorded date, not the day an old snapshot happens to be reprocessed.
  const date = args[index + 1].match(/snapshot-(\d{4})(\d{2})(\d{2})/)?.slice(1).join("-") ?? "undated";
  await writeFile("docs/MISSING-CAR-CATALOGUE.md", coverageMarkdown(generations, rows, date));
  console.log(`${rows.filter((r) => r.state !== "present").length} absent candidates → docs/MISSING-CAR-CATALOGUE.md`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
