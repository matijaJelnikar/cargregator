// Step 2 of the CO2 data (docs/CO2.md): EEA groups from ingest.ts → one row per model, fuel, kW and registration
// year in src/data/co2/<makeId>.json. Plain rules only (names.ts); names no rule matches go to the report.
//
//   node scripts/co2/build.ts              # every make with ingested data
//   node scripts/co2/build.ts volkswagen   # some makes

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { MAKES, type Make } from "../../src/data/makes.ts";
import type { Co2Data, Co2Row } from "../../src/lib/co2.ts";
import type { EuroNorm } from "../../src/lib/dmv.ts";
import type { Group, Hist } from "./ingest.ts";
import { modelFor } from "./names.ts";
import { mergeHists, toEuro, toFuel, toStat } from "./normalize.ts";

/** Rows with fewer registrations are dropped as typos and one-offs. */
const MIN_CARS = 20;
/** Highest believable WLTP/NEDC ratio for one engine; outside 1.0–1.45 one of the figures is junk. */
const WLTP_NEDC_MAX = 1.45;

const ROOT = new URL("../../", import.meta.url);
const GROUPS = new URL("data-raw/eea/groups/", ROOT);
const REPORTS = new URL("data-raw/co2/reports/", ROOT);
const OUTPUT = new URL("src/data/co2/", ROOT);

interface Acc {
  wltp: Hist[];
  nedc: Hist[];
  cars: number;
  euro: Map<EuroNorm, number>;
}

async function build(make: Make) {
  const groups = JSON.parse(await readFile(new URL(`${make.id}.json`, GROUPS), "utf8")) as Group[];
  const rows = new Map<string, Acc>();
  const unmatched = new Map<string, number>();
  let total = 0;
  let matched = 0;
  const notes: string[] = [];

  for (const g of groups) {
    const kind = toFuel(g);
    if (!kind || g.kw === null) continue;
    total += g.n;
    const modelId = modelFor(make, g.cn);
    if (!modelId) {
      unmatched.set(g.cn, (unmatched.get(g.cn) ?? 0) + g.n);
      continue;
    }
    matched += g.n;
    const diesel = kind.scale === "diesel" && kind.fuel !== "diesel";
    const key = [modelId, kind.fuel, diesel ? 1 : 0, Math.round(g.kw), g.year].join("|");
    const acc: Acc = rows.get(key) ?? { wltp: [], nedc: [], cars: 0, euro: new Map() };
    acc.wltp.push(g.wltp);
    acc.nedc.push(g.nedc);
    acc.cars += g.n;
    const euro = toEuro(g.ech);
    if (euro) acc.euro.set(euro, (acc.euro.get(euro) ?? 0) + g.n);
    rows.set(key, acc);
  }

  const data: Co2Data = {};
  for (const [key, acc] of rows) {
    if (acc.cars < MIN_CARS) continue;
    const [modelId, fuel, diesel, kw, year] = key.split("|");
    let wltp = toStat(mergeHists(acc.wltp))?.median ?? null;
    let nedc = toStat(mergeHists(acc.nedc))?.median ?? null;
    if (wltp !== null && nedc !== null && fuel !== "electric" && nedc > 0) {
      const ratio = wltp / nedc;
      if (ratio > WLTP_NEDC_MAX) {
        notes.push(`${key}: WLTP ${wltp} vs NEDC ${nedc}, WLTP dropped`);
        wltp = null;
      } else if (ratio < 1) {
        notes.push(`${key}: NEDC ${nedc} above WLTP ${wltp}, NEDC dropped`);
        nedc = null;
      }
    }
    if (wltp === null && nedc === null && fuel !== "electric") continue;
    const euro = [...acc.euro].sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;
    const row: Co2Row = [fuel as Co2Row[0], Number(diesel) as 0 | 1, Number(kw), Number(year), wltp, nedc, acc.cars, euro];
    (data[modelId] ??= []).push(row);
  }
  for (const list of Object.values(data)) list.sort((a, b) => a[0].localeCompare(b[0]) || a[2] - b[2] || a[3] - b[3]);

  await writeFile(new URL(`${make.id}.json`, OUTPUT), JSON.stringify(data));

  const share = total ? Math.round((matched / total) * 1000) / 10 : 0;
  const missing = make.models.filter((m) => !data[m.id]).map((m) => m.name);
  const top = [...unmatched].sort((a, b) => b[1] - a[1]).slice(0, 60);
  await writeFile(
    new URL(`${make.id}.md`, REPORTS),
    [
      `# ${make.name}`,
      "",
      `Registrations matched to a model: ${share} % (${matched} of ${total}).`,
      "",
      `Models without data: ${missing.join(", ") || "none"}.`,
      "",
      "## Biggest unmatched names",
      "",
      ...top.map(([cn, n]) => `- ${cn || "(empty)"}: ${n}`),
      "",
      "## Dropped figures",
      "",
      ...(notes.length ? notes.map((n) => `- ${n}`) : ["none"]),
      "",
    ].join("\n"),
  );
  const rowCount = Object.values(data).reduce((s, l) => s + l.length, 0);
  console.log(`${make.id}: ${share} % matched, ${rowCount} rows, ${missing.length} models without data`);
}

async function writeIndex() {
  const ids = (await readdir(OUTPUT)).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
  const lines = ids.map((id) => `  ${JSON.stringify(id)}: () => import("./${id}.json").then((m) => m.default as unknown as Co2Data),`);
  await writeFile(
    new URL("index.ts", OUTPUT),
    `// Generated by scripts/co2/build.ts; do not edit.\n\nimport type { Co2Data } from "@/lib/co2";\n\n` +
      `export const CO2_LOADERS: Record<string, () => Promise<Co2Data>> = {\n${lines.join("\n")}\n};\n`,
  );
}

await mkdir(REPORTS, { recursive: true });
await mkdir(OUTPUT, { recursive: true });
const wanted = process.argv.slice(2);
const available = MAKES.filter((m) => existsSync(new URL(`${m.id}.json`, GROUPS)));
for (const make of wanted.length ? available.filter((m) => wanted.includes(m.id)) : available) await build(make);
await writeIndex();
